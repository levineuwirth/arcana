//! Painted Bluffs — nonbasic land — Desert (Amonkhet).
//! "{T}: Add {C}." and "{1}, {T}: Add one mana of any color."
//!
//! The any-color filter is modeled as FIVE separate mana abilities,
//! one per WUBRG color — choosing which to activate IS the color
//! choice (the catalog-wide idiom).

use arcana_core::effects::Effect;
use arcana_core::mana::{ManaCost, ManaUnit};
use arcana_core::objects::Characteristics;
use arcana_core::registry::{
    ActivatedAbilityDef, ActivationContext, ActivationCost, ActivationZone,
    CardDefinition, CardRegistry,
};
use arcana_core::state::GameState;
use arcana_core::types::{CardId, ColorSet, ManaColor, SubtypeSet, TypeLine};

pub fn register(reg: &mut CardRegistry) -> CardId {
    let name = reg.interner_mut().intern("Painted Bluffs");
    let desert = reg.interner_mut().intern("Desert");
    let mut subtypes = SubtypeSet::default();
    subtypes.0.insert(desert);
    let chars = Characteristics {
        name,
        mana_cost: None,
        colors: ColorSet::new(),
        types: TypeLine::LAND.into(),
        subtypes,
        ..Default::default()
    };
    let mut def = CardDefinition::new(name, chars).with_activated_ability(
        ActivatedAbilityDef {
            text: "{T}: Add {C}.".into(),
            cost: ActivationCost::tap_only(),
            target_requirements: Vec::new(),
            is_mana_ability: true,
            is_loyalty_ability: false,
            activation_zone: ActivationZone::Battlefield,
            is_instant_speed: false,
            face_gate: None,
            effect: add_colorless_mana,
        },
    );
    let any_color: [(&str, _); 5] = [
        ("{1}, {T}: Add {W}.", add_white_mana as fn(&GameState, &ActivationContext, &CardRegistry) -> Vec<Effect>),
        ("{1}, {T}: Add {U}.", add_blue_mana),
        ("{1}, {T}: Add {B}.", add_black_mana),
        ("{1}, {T}: Add {R}.", add_red_mana),
        ("{1}, {T}: Add {G}.", add_green_mana),
    ];
    for (text, effect) in any_color {
        def = def.with_activated_ability(ActivatedAbilityDef {
            text: text.into(),
            cost: ActivationCost {
                mana_cost: ManaCost::parse("{1}").expect("valid cost"),
                tap: true,
                ..ActivationCost::default()
            },
            target_requirements: Vec::new(),
            is_mana_ability: true,
            is_loyalty_ability: false,
            activation_zone: ActivationZone::Battlefield,
            is_instant_speed: false,
            face_gate: None,
            effect,
        });
    }
    reg.register(def)
}

fn add_colorless_mana(
    _state: &GameState,
    ctx: &ActivationContext,
    _reg: &CardRegistry,
) -> Vec<Effect> {
    vec![Effect::AddMana {
        player: ctx.controller,
        mana: vec![ManaUnit::plain(ManaColor::Colorless, ctx.source)],
    }]
}

