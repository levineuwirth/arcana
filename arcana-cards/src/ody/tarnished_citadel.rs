//! Tarnished Citadel — nonbasic land (Odyssey, 2001).
//! "{T}: Add {C}." and "{T}: Add one mana of any color. This land
//! deals 3 damage to you." The any-color ability is five mana
//! abilities, one per WUBRG color.
//!
//! GAP: the "this land deals 3 damage to you" rider on the colored
//! mana abilities is not expressible on a mana ability (an effect
//! beyond AddMana would forfeit mana-ability status) — the plain mana
//! abilities are emitted without the self-damage.

use arcana_core::effects::Effect;
use arcana_core::mana::ManaUnit;
use arcana_core::objects::Characteristics;
use arcana_core::registry::{
    ActivatedAbilityDef, ActivationContext, ActivationCost, ActivationZone,
    CardDefinition, CardRegistry,
};
use arcana_core::state::GameState;
use arcana_core::types::{CardId, ColorSet, ManaColor, TypeLine};

pub fn register(reg: &mut CardRegistry) -> CardId {
    let name = reg.interner_mut().intern("Tarnished Citadel");
    let chars = Characteristics {
        name,
        mana_cost: None,
        colors: ColorSet::new(),
        types: TypeLine::LAND.into(),
        ..Default::default()
    };
    // GAP: 'This land deals 3 damage to you' rider on the any-color
    // mana ability — a damage rider on a mana ability is not
    // expressible; plain mana abilities emitted.
    reg.register(
        CardDefinition::new(name, chars)
            .with_activated_ability(ability("{T}: Add {C}.", add_colorless))
            .with_activated_ability(ability("{T}: Add {W}.", add_white))
            .with_activated_ability(ability("{T}: Add {U}.", add_blue))
            .with_activated_ability(ability("{T}: Add {B}.", add_black))
            .with_activated_ability(ability("{T}: Add {R}.", add_red))
            .with_activated_ability(ability("{T}: Add {G}.", add_green)),
    )
}

fn ability(
    text: &str,
    effect: fn(&GameState, &ActivationContext, &CardRegistry) -> Vec<Effect>,
) -> ActivatedAbilityDef {
    ActivatedAbilityDef {
        text: text.into(),
        cost: ActivationCost::tap_only(),
        target_requirements: Vec::new(),
        is_mana_ability: true,
        is_loyalty_ability: false,
        activation_zone: ActivationZone::Battlefield,
        is_instant_speed: false,
        face_gate: None,
        effect,
    }
}

fn add_colorless(
    _state: &GameState,
    ctx: &ActivationContext,
    _reg: &CardRegistry,
) -> Vec<Effect> {
    vec![Effect::AddMana {
        player: ctx.controller,
        mana: vec![ManaUnit::plain(ManaColor::Colorless, ctx.source)],
    }]
}

