//! Oathsworn Giant — `{4}{W}{W}` 3/4 white Giant Soldier with Vigilance.
//!
//! Oracle:
//! * Vigilance
//! * Other creatures you control get +0/+2 and have vigilance. (static anthem — GAP)

use arcana_core::effects::KeywordAbility;
use arcana_core::mana::ManaCost;
use arcana_core::objects::Characteristics;
use arcana_core::registry::{CardDefinition, CardRegistry};
use arcana_core::types::{CardId, ColorSet, PtValue, SubtypeSet, TypeLine};

pub fn register(reg: &mut CardRegistry) -> CardId {
    let name = reg.interner_mut().intern("Oathsworn Giant");
    let giant = reg.interner_mut().intern("Giant");
    let soldier = reg.interner_mut().intern("Soldier");
    let mut subtypes = SubtypeSet::default();
    subtypes.0.insert(giant);
    subtypes.0.insert(soldier);

    let chars = Characteristics {
        name,
        mana_cost: Some(ManaCost::parse("{4}{W}{W}").expect("valid cost")),
        colors: ColorSet::white(),
        types: TypeLine::CREATURE.into(),
        subtypes,
        power: Some(PtValue::Fixed(3)),
        toughness: Some(PtValue::Fixed(4)),
        keywords: vec![KeywordAbility::Vigilance],
        ..Default::default()
    };

    // GAP: static continuous anthem "Other creatures you control get +0/+2
    // and have vigilance" — not expressible as a triggered/activated ability.
    reg.register(CardDefinition::new(name, chars))
}
